"use client";

import * as React from "react";
import { useQuery } from "@tanstack/react-query";
import { reportsService } from "@/services/reports.service";
import { PageHeader } from "@/components/shared/page-header";
import { LoadingState } from "@/components/shared/loading-state";
import { DataTable } from "@/components/shared/data-table";
import { Card, CardHeader, CardTitle, CardDescription, CardContent } from "@/components/ui/card";
import { Button } from "@/components/ui/button";
import {
  Download,
  FileSpreadsheet,
  TrendingUp,
  Package,
  Users,
  MessageSquare,
  BarChart3,
} from "lucide-react";
import { toast } from "sonner";
import { cn } from "@/lib/utils";

const REPORT_DEFINITIONS = [
  { id: "dm_funnel", title: "DM Funnel Conversion", icon: MessageSquare, desc: "Drop-off analytics from comment to payment" },
  { id: "product_attribution", title: "Product DM Attribution", icon: Package, desc: "Sales generated by comment automation links" },
  { id: "customer_cohorts", title: "Customer Cohort Audit", icon: Users, desc: "LTV and repeat purchase breakdown" },
  { id: "automation_audits", title: "Automation Engine Health", icon: TrendingUp, desc: "Execution speed and error rates" },
  { id: "message_logs", title: "Raw Message Dispatch", icon: FileSpreadsheet, desc: "Timestamped logs of every outbound DM" },
  { id: "campaign_roi", title: "Campaign ROI & ROAS", icon: BarChart3, desc: "Revenue per automated engagement" },
];

export default function ReportsPage() {
  const [selectedReport, setSelectedReport] = React.useState("dm_funnel");
  const [dateRange, setDateRange] = React.useState("30d");

  const { data: reportData, isLoading } = useQuery({
    queryKey: ["report", selectedReport, dateRange],
    queryFn: () => reportsService.generateReport(selectedReport, { range: dateRange }).then((res) => res.data),
  });

  const handleDownloadReport = () => {
    toast.success(`Exporting "${REPORT_DEFINITIONS.find((r) => r.id === selectedReport)?.title}" as CSV...`);
  };

  const activeDef = REPORT_DEFINITIONS.find((r) => r.id === selectedReport) || REPORT_DEFINITIONS[0];

  return (
    <div className="space-y-6">
      <PageHeader
        title="Custom Reports & Auditing"
        description="Comprehensive audit exports covering marketing funnels, delivery performance, and revenue attribution."
      >
        <div className="flex items-center gap-2">
          {/* Simulated Download Button */}
          <Button
            size="sm"
            onClick={handleDownloadReport}
            className="gap-1.5 shadow-xs text-xs"
          >
            <Download className="h-4 w-4" />
            <span>Download PDF / XLSX</span>
          </Button>
        </div>
      </PageHeader>

      {/* Six Report Switcher Cards */}
      <div className="grid grid-cols-2 md:grid-cols-3 lg:grid-cols-6 gap-3">
        {REPORT_DEFINITIONS.map((rep) => {
          const Icon = rep.icon;
          const isSelected = selectedReport === rep.id;
          return (
            <button
              key={rep.id}
              onClick={() => setSelectedReport(rep.id)}
              className={cn(
                "p-3.5 rounded-[12px] border text-left transition-all flex flex-col justify-between cursor-pointer",
                isSelected
                  ? "bg-card border-primary ring-2 ring-primary/20 shadow-xs"
                  : "bg-card border-border hover:border-primary/50 hover:bg-muted/50"
              )}
            >
              <div
                className={cn(
                  "flex h-8 w-8 items-center justify-center rounded-[8px] mb-2 transition-colors",
                  isSelected ? "bg-primary text-primary-foreground" : "bg-secondary text-muted-foreground"
                )}
              >
                <Icon className="h-4 w-4" />
              </div>
              <div>
                <h4
                  className={cn(
                    "text-xs font-bold transition-colors",
                    isSelected ? "text-primary" : "text-foreground"
                  )}
                >
                  {rep.title}
                </h4>
                <p className="text-[10px] text-muted-foreground mt-0.5 line-clamp-2 leading-tight">
                  {rep.desc}
                </p>
              </div>
            </button>
          );
        })}
      </div>

      {/* Report Preview & Table */}
      <Card>
        <CardHeader className="flex flex-col sm:flex-row sm:items-center sm:justify-between pb-4 border-b border-border">
          <div>
            <div className="flex items-center gap-2">
              <CardTitle>{reportData?.title || activeDef.title}</CardTitle>
              <span className="text-[10px] font-bold bg-primary-soft text-primary px-2 py-0.5 rounded-full">
                Live Data Preview
              </span>
            </div>
            <CardDescription className="mt-1">
              {reportData?.description || activeDef.desc}
            </CardDescription>
          </div>

          <div className="flex items-center gap-2 mt-3 sm:mt-0">
            {/* Date range filter */}
            <div className="flex items-center gap-1 bg-secondary p-0.5 rounded-[8px] border border-border">
              {["7d", "30d", "90d", "All Time"].map((d) => (
                <button
                  key={d}
                  onClick={() => setDateRange(d)}
                  className={cn(
                    "px-2.5 py-1 text-xs rounded-[6px] font-medium transition-colors cursor-pointer",
                    dateRange === d
                      ? "bg-card text-foreground shadow-xs"
                      : "text-muted-foreground hover:text-foreground"
                  )}
                >
                  {d}
                </button>
              ))}
            </div>
          </div>
        </CardHeader>

        <CardContent className="p-5">
          {isLoading ? (
            <LoadingState text="Compiling dataset..." />
          ) : (
            <DataTable
              columns={reportData?.columns || []}
              data={reportData?.rows || []}
              isLoading={false}
              exportFilename={`${selectedReport}_report`}
              searchable={true}
              searchPlaceholder="Filter report records..."
            />
          )}
        </CardContent>
      </Card>
    </div>
  );
}
